#!/usr/bin/env node
// Regenerates src/lib/database.generated.ts from the LOCAL Supabase stack (`pnpm db:reset` first).
// CI runs this and fails when the committed file differs (review finding 4.5).
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const target = resolve(root, "src/lib/database.generated.ts");
const generated = execFileSync(
  "pnpm",
  ["exec", "supabase", "gen", "types", "typescript", "--schema", "public"],
  { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] },
);
const header = [
  "// Generated by `pnpm db:types` from the local Supabase stack. Do not edit by hand.",
  "// Nullable RPC arguments and app-level aliases live in database.types.ts.",
  "",
  "",
].join("\n");

writeFileSync(target, header + generated);
execFileSync("pnpm", ["exec", "prettier", "--write", target], { cwd: root, stdio: "ignore" });
process.stdout.write(`Wrote ${target}\n`);
